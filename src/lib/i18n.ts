const dictionaries: Record<Locale, Record<MessageKey, string>> = {
  en,
  ja,
  "zh-Hant": zhHant,
  "zh-Hans": zhHans,
};

let currentLocale: Locale = DEFAULT_LOCALE;

const LOCALE_PREFIXES: [string, Locale][] = [
  ["zh-hant", "zh-Hant"],
  ["zh-hans", "zh-Hans"],
  ["zh-tw", "zh-Hant"],
  ["zh-hk", "zh-Hant"],
  ["zh-mo", "zh-Hant"],
  ["zh-cht", "zh-Hant"],
  ["zh-cn", "zh-Hans"],
  ["zh-sg", "zh-Hans"],
  ["zh-chs", "zh-Hans"],
  ["zh", "zh-Hans"],
  ["ja", "ja"],
];

export function detectLocale(lang?: string): Locale {
  // Node 21+ exposes `navigator` (and CI is usually en-US). Only trust a
  // real browser so SSR, tests, and prerender keep DEFAULT_LOCALE.
  const fromBrowser =
    typeof window !== "undefined" && typeof navigator !== "undefined"
      ? navigator.languages?.[0] || navigator.language
      : undefined;
  const raw = lang || fromBrowser || DEFAULT_LOCALE;
  const lower = String(raw || DEFAULT_LOCALE).toLowerCase();
  for (const [prefix, id] of LOCALE_PREFIXES) {
    if (lower === prefix || lower.startsWith(prefix + "-")) return id;
  }
  return "en";
}

export function htmlLang(locale: Locale): string {
  return locale;
}

export function setLocale(locale: Locale) {
  currentLocale = locale;
}

export function getLocale(): Locale {
  return currentLocale;
}

export function t(
  key: MessageKey,
  vars?: Record<string, string | number>,
  locale: Locale = currentLocale,
): string {
  const dict = dictionaries[locale] || dictionaries.en;
  let out = dict[key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, String(value));
    }
  }
  return out;
}

export function applyDocumentLocale(locale: Locale, titleKey: MessageKey = "metaTitle") {
  if (typeof document === "undefined") return;
  document.documentElement.lang = htmlLang(locale);
  document.documentElement.dir = "ltr";
  document.title = t(titleKey, undefined, locale);
}
